"""
gen_web_pages.py — writes src/web_pages.inc: the phone / tablet page and the OBS browser source
page of makine_live/tv/subtitle_web.py, as C++ raw strings, so the plugin serves exactly the
pages the harness serves.

    python tools/gen_web_pages.py
"""

import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from makine_live.tv import subtitle_web  # noqa: E402

OUT = os.path.join(ROOT, "src", "web_pages.inc")
with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
    fh.write("// Generated by tools/gen_web_pages.py from makine_live/tv/subtitle_web.py. Do not edit.\n")
    for name, page in (("kPhoneHtml", subtitle_web.PHONE_HTML), ("kObsHtml", subtitle_web.OBS_HTML)):
        assert ")PAGE\"" not in page
        fh.write(f"static const char {name}[] = R\"PAGE({page})PAGE\";\n")
print(OUT)
