"""
gen_unicode.py — writes src/unicode_data.inc: the character properties the C++ text
rules need, taken from this Python's unicodedata / str methods.

    python tools/gen_unicode.py

The C++ port of the Python text rules (normalize_dialogue_text, garbage_reason,
filter_ocr, LineTracker) must classify characters exactly as Python does; the C
runtime's iswalpha/towlower differ. Regenerate when the Python side moves to a new
Unicode version and commit the result.
"""

import os
import sys
import unicodedata

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "src", "unicode_data.inc")

# Bit order must match src/unitext.cpp.
FLAGS = [
    ("ALPHA", str.isalpha),
    ("DECIMAL", str.isdecimal),
    ("DIGIT", str.isdigit),
    ("NUMERIC", str.isnumeric),
    ("LOWER", str.islower),
    ("UPPER", str.isupper),
    ("TITLE", lambda c: unicodedata.category(c) == "Lt"),   # str.istitle() is also true for "A"
    ("SPACE", str.isspace),
    ("NUMBER", lambda c: unicodedata.category(c)[0] == "N"),
    ("CASED", lambda c: c.islower() or c.isupper() or c.istitle()),
    ("CASE_IGNORABLE", lambda c: unicodedata.category(c) in ("Mn", "Me", "Cf", "Lm", "Sk")
                                 or c in "'.:^`­··՟״‘’․‧︓﹒﹕＇．："),
]


def flags_of(cp: int) -> int:
    c = chr(cp)
    if 0xD800 <= cp <= 0xDFFF:
        return 0
    v = 0
    for bit, (_, fn) in enumerate(FLAGS):
        if fn(c):
            v |= 1 << bit
    return v


def main():
    runs = []   # (start, flags)
    prev = None
    for cp in range(sys.maxunicode + 1):
        f = flags_of(cp)
        if f != prev:
            runs.append((cp, f))
            prev = f
    lower = []
    for cp in range(sys.maxunicode + 1):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        lo = chr(cp).lower()
        if len(lo) == 1 and ord(lo) != cp:
            lower.append((cp, ord(lo)))
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("// Generated by tools/gen_unicode.py from Python %s (Unicode %s). Do not edit.\n"
                 % (sys.version.split()[0], unicodedata.unidata_version))
        for bit, (name, _) in enumerate(FLAGS):
            fh.write(f"// bit {bit}: {name}\n")
        fh.write("static constexpr CharRun kRuns[] = {\n")
        for i in range(0, len(runs), 6):
            fh.write("    " + " ".join(f"{{0x{s:X}, 0x{f:X}}}," for s, f in runs[i:i + 6]) + "\n")
        fh.write("};\n")
        fh.write("static constexpr LowerPair kLower[] = {\n")
        for i in range(0, len(lower), 6):
            fh.write("    " + " ".join(f"{{0x{a:X}, 0x{b:X}}}," for a, b in lower[i:i + 6]) + "\n")
        fh.write("};\n")
    print(f"{OUT}: {len(runs)} runs, {len(lower)} lowercase pairs")


if __name__ == "__main__":
    main()
